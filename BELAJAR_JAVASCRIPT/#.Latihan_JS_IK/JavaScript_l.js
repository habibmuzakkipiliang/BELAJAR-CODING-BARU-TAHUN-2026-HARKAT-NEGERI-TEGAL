// Switch Case dengan rambu lalu lintas 

var lampu = "Merah"

switch (lampu) {

    case "Merah":
        console.log ("Merah, berhenti")
        break

    case "Kuning":
        console.log ("Kuning, bersiap-siap")
        break

    case "Hijau":
        console.log ("Hijau, jalan")
        break

    default:
        console.log ("Rambu tidak dikenal")

}


console.log ("\n --- batas --- \n")




