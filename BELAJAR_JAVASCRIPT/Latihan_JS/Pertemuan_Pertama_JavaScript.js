// Percabangan Nested

var j = 9
var cek = true

if (j >= 8) {
    if (cek) {
        console.log (`Besar, angka j = ${j}`)
    }

    else {
        console.log (`Sedang, angka j = ${j}`)
    }
}

else {
    console.log (`Kecil, angka j = ${j}`)
}


console.log ("\n --- batas --- \n")



